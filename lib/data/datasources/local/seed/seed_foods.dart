import '../../../models/food_item_model.dart';
import 'seed_restaurants.dart';

/// Compact seed description of one dish. Ids, restaurant names and image
/// handling are filled in by [buildSeedFoods] so the literal list below stays
/// readable.
class _Dish {
  const _Dish(
    this.name,
    this.description,
    this.price,
    this.categoryId,
    this.emoji, {
    this.discount,
    this.rating = 4.5,
    this.reviews = 120,
    this.ingredients = const <String>[],
    this.allergens = const <String>[],
    this.veg = false,
    this.spicy = false,
    this.spiceLevel = 0,
    this.kcal,
    this.prep = 15,
    this.popular = false,
    this.available = true,
    this.serving,
  });

  final String name;
  final String description;
  final double price;
  final String categoryId;
  final String emoji;
  final double? discount;
  final double rating;
  final int reviews;
  final List<String> ingredients;
  final List<String> allergens;
  final bool veg;
  final bool spicy;
  final int spiceLevel;
  final int? kcal;
  final int prep;
  final bool popular;
  final bool available;
  final String? serving;
}

/// 100 dishes - five for each of the 20 seeded restaurants.
List<FoodItemModel> buildSeedFoods() {
  final List<FoodItemModel> items = <FoodItemModel>[];

  _menu.forEach((String restaurantId, List<_Dish> dishes) {
    final String restaurantName = kSeedRestaurants
        .firstWhere((dynamic r) => r.id == restaurantId)
        .name;
    for (int i = 0; i < dishes.length; i++) {
      final _Dish d = dishes[i];
      items.add(
        FoodItemModel(
          id: '$restaurantId-f${(i + 1).toString().padLeft(2, '0')}',
          restaurantId: restaurantId,
          restaurantName: restaurantName,
          name: d.name,
          description: d.description,
          priceMyr: d.price,
          discountPriceMyr: d.discount,
          categoryId: d.categoryId,
          emoji: d.emoji,
          rating: d.rating,
          reviewCount: d.reviews,
          ingredients: d.ingredients,
          allergens: d.allergens,
          isVegetarian: d.veg,
          isSpicy: d.spicy,
          spiceLevel: d.spiceLevel,
          calories: d.kcal,
          prepMinutes: d.prep,
          isAvailable: d.available,
          isPopular: d.popular,
          servingSize: d.serving,
        ),
      );
    }
  });

  return items;
}

