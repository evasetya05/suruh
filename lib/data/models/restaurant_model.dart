import '../../domain/entities/restaurant.dart';
import 'address_model.dart';

class RestaurantModel extends Restaurant {
  const RestaurantModel({
    required super.id,
    required super.name,
    required super.cuisines,
    required super.emoji,
    required super.rating,
    required super.reviewCount,
    required super.deliveryFeeMyr,
    required super.minOrderMyr,
    required super.etaMinMinutes,
    required super.etaMaxMinutes,
    required super.distanceKm,
    required super.address,
    super.imageUrl,
    super.coverImageUrl,
    super.description,
    super.isOpen,
    super.isPromoted,
    super.promoText,
    super.priceLevel,
    super.tags,
    super.openingTime,
    super.closingTime,
    super.ownerId,
    super.phone,
  });

  factory RestaurantModel.fromEntity(Restaurant r) => RestaurantModel(
        id: r.id,
        name: r.name,
        cuisines: r.cuisines,
        emoji: r.emoji,
        rating: r.rating,
        reviewCount: r.reviewCount,
        deliveryFeeMyr: r.deliveryFeeMyr,
        minOrderMyr: r.minOrderMyr,
        etaMinMinutes: r.etaMinMinutes,
        etaMaxMinutes: r.etaMaxMinutes,
        distanceKm: r.distanceKm,
        address: r.address,
        imageUrl: r.imageUrl,
        coverImageUrl: r.coverImageUrl,
        description: r.description,
        isOpen: r.isOpen,
        isPromoted: r.isPromoted,
        promoText: r.promoText,
        priceLevel: r.priceLevel,
        tags: r.tags,
        openingTime: r.openingTime,
        closingTime: r.closingTime,
        ownerId: r.ownerId,
        phone: r.phone,
      );

  factory RestaurantModel.fromJson(Map<String, dynamic> json) =>
      RestaurantModel(
        id: json['id'] as String,
        name: json['name'] as String,
        cuisines:
            (json['cuisines'] as List<dynamic>? ?? <dynamic>[]).cast<String>(),
        emoji: json['emoji'] as String? ?? '🍽️',
        rating: (json['rating'] as num).toDouble(),
        reviewCount: json['reviewCount'] as int? ?? 0,
        deliveryFeeMyr: (json['deliveryFeeMyr'] as num).toDouble(),
        minOrderMyr: (json['minOrderMyr'] as num).toDouble(),
        etaMinMinutes: json['etaMinMinutes'] as int,
        etaMaxMinutes: json['etaMaxMinutes'] as int,
        distanceKm: (json['distanceKm'] as num).toDouble(),
        address:
            AddressModel.fromJson(json['address'] as Map<String, dynamic>),
        imageUrl: json['imageUrl'] as String?,
        coverImageUrl: json['coverImageUrl'] as String?,
        description: json['description'] as String? ?? '',
        isOpen: json['isOpen'] as bool? ?? true,
        isPromoted: json['isPromoted'] as bool? ?? false,
        promoText: json['promoText'] as String?,
        priceLevel: json['priceLevel'] as int? ?? 2,
        tags: (json['tags'] as List<dynamic>? ?? <dynamic>[]).cast<String>(),
        openingTime: json['openingTime'] as String? ?? '10:00',
        closingTime: json['closingTime'] as String? ?? '22:00',
        ownerId: json['ownerId'] as String?,
        phone: json['phone'] as String?,
      );

  Map<String, dynamic> toJson() => <String, dynamic>{
        'id': id,
        'name': name,
        'cuisines': cuisines,
        'emoji': emoji,
        'rating': rating,
        'reviewCount': reviewCount,
        'deliveryFeeMyr': deliveryFeeMyr,
        'minOrderMyr': minOrderMyr,
        'etaMinMinutes': etaMinMinutes,
        'etaMaxMinutes': etaMaxMinutes,
        'distanceKm': distanceKm,
        'address': AddressModel.fromEntity(address).toJson(),
        'imageUrl': imageUrl,
        'coverImageUrl': coverImageUrl,
        'description': description,
        'isOpen': isOpen,
        'isPromoted': isPromoted,
        'promoText': promoText,
        'priceLevel': priceLevel,
        'tags': tags,
        'openingTime': openingTime,
        'closingTime': closingTime,
        'ownerId': ownerId,
        'phone': phone,
      };
}
